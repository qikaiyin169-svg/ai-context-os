"""Preview, hash-confirmed apply, exact backups, guarded rollback."""

import difflib
import json
import re
import uuid
from pathlib import Path

from .router import applicable, conflicts, normalized
from .util import (
    AicoError,
    atomic_write,
    digest,
    encode,
    no_links,
    private_dir,
    read_json,
)

START = "<!-- aico:begin v0.1 -->"
END = "<!-- aico:end -->"
SKILL_MARKER = "<!-- Generated by AI Context OS v0.1 -->"


def render(rules, scope, project):
    active = [
        r
        for r in rules
        if r["status"] == "approved"
        and applicable(r, project)
        and (r["kind"] == "skill" or r["kind"] == scope)
        and (bool(r["project"]) == (scope == "project"))
    ]
    # Global guidance is installed separately; detect all applicable collisions first.
    all_active = [
        r for r in rules if r["status"] == "approved" and applicable(r, project)
    ]
    if conflicts(all_active):
        raise AicoError(
            "Resolve explicit conflicts before native export (native precedence may differ)"
        )
    result, lines, seen = {}, [], set()
    for rule in active:
        if START in rule["text"] or END in rule["text"]:
            raise AicoError("Reserved AICO markers in rule text")
        if rule["kind"] == "skill":
            name = rule["name"]
            relative = ".agents/skills/" + name + "/SKILL.md"
            if relative in result:
                raise AicoError("Duplicate skill name: " + name)
            description = rule["description"] or "Use when task contains: " + ", ".join(
                rule["triggers"]
            )
            result[relative] = (
                "---\nname: "
                + json.dumps(name)
                + "\ndescription: "
                + json.dumps(description, ensure_ascii=False)
                + "\n---\n\n"
                + SKILL_MARKER
                + "\n"
                + rule["text"].strip()
                + "\n"
            )
        elif normalized(rule["text"]) not in seen:
            lines.append("- " + rule["text"].strip().replace("\n", "\n  "))
            seen.add(normalized(rule["text"]))
    result["AGENTS.md"] = (
        START
        + "\n# AI Context OS reviewed rules\n"
        + "\n".join(lines)
        + "\n"
        + END
        + "\n"
    )
    return result


def merge_agents(before, block):
    text = before.decode("utf-8") if before is not None else ""
    if text.count(START) != text.count(END) or text.count(START) > 1:
        raise AicoError("Malformed/duplicate AICO block; repair manually")
    if START in text and text.index(START) > text.index(END):
        raise AicoError("AICO end marker precedes start marker")
    if START in text:
        pattern = re.escape(START) + r".*?" + re.escape(END) + r"\n?"
        return re.sub(pattern, lambda _: block, text, flags=re.S).encode("utf-8")
    return (text + ("\n" if text and not text.endswith("\n") else "") + block).encode(
        "utf-8"
    )


def current(path):
    path = no_links(path)
    if path.exists():
        if not path.is_file() or path.stat().st_size > 2_000_000:
            raise AicoError("Target must be a regular file <=2 MB")
        return path.read_bytes()
    return None


def sha(data):
    return None if data is None else digest(data)


def plan(files, agents_file, skills_dir):
    changes = []
    for rel, text in sorted(files.items()):
        target = (
            Path(agents_file)
            if rel == "AGENTS.md"
            else Path(skills_dir) / Path(rel).relative_to(".agents/skills")
        )
        target = no_links(target)
        if target.name not in ("AGENTS.md", "SKILL.md"):
            raise AicoError("Only AGENTS.md and SKILL.md targets are supported")
        before = current(target)
        if rel == "AGENTS.md":
            override = target.with_name("AGENTS.override.md")
            if override.exists():
                raise AicoError(
                    "AGENTS.override.md shadows this target; inspect it before installation"
                )
            after = merge_agents(before, text)
        else:
            if before is not None and SKILL_MARKER.encode() not in before:
                raise AicoError(
                    "Existing unmanaged skill; choose another name: " + str(target)
                )
            after = text.encode("utf-8")
        if before != after:
            changes.append(
                {
                    "path": str(target),
                    "before_sha256": sha(before),
                    "after": after.decode("utf-8"),
                    "diff": "".join(
                        difflib.unified_diff(
                            (before or b"").decode("utf-8").splitlines(True),
                            after.decode("utf-8").splitlines(True),
                            fromfile=str(target),
                            tofile=str(target),
                        )
                    ),
                }
            )
    return {"schema": 1, "changes": changes}


def confirmation(plan_data):
    return digest(encode(plan_data))


def checked_changes(plan_data):
    if plan_data.get("schema") != 1 or not isinstance(plan_data.get("changes"), list):
        raise AicoError("Invalid install plan")
    paths = set()
    for change in plan_data["changes"]:
        path = no_links(change["path"])
        if (
            not path.is_absolute()
            or path.name not in ("AGENTS.md", "SKILL.md")
            or str(path) in paths
        ):
            raise AicoError("Invalid or duplicate plan target")
        paths.add(str(path))
        if sha(current(path)) != change["before_sha256"]:
            raise AicoError(
                "Target changed since preview; create a new plan: " + str(path)
            )
        if path.name == "AGENTS.md" and path.with_name("AGENTS.override.md").exists():
            raise AicoError("Target became shadowed since preview")
    return plan_data["changes"]


def apply(plan_data, home, confirm):
    if confirm != confirmation(plan_data):
        raise AicoError("Confirmation hash does not match reviewed plan")
    changes = checked_changes(plan_data)
    install_id = uuid.uuid4().hex
    folder = private_dir(Path(home) / "backups" / install_id)
    manifest = {"schema": 1, "id": install_id, "state": "prepared", "changes": []}
    for i, change in enumerate(changes):
        path = no_links(change["path"])
        before = current(path)
        mode = path.stat().st_mode & 0o777 if before is not None else 0o600
        if before is not None:
            atomic_write(folder / (str(i) + ".bak"), before)
        manifest["changes"].append(
            {
                "path": str(path),
                "existed": before is not None,
                "before_sha256": sha(before),
                "after_sha256": digest(change["after"].encode()),
                "mode": mode,
            }
        )
    atomic_write(folder / "manifest.json", encode(manifest))
    applied = []
    try:
        for i, change in enumerate(changes):
            path = no_links(change["path"])
            if sha(current(path)) != change["before_sha256"]:
                raise AicoError("Concurrent modification detected")
            atomic_write(
                path, change["after"].encode("utf-8"), manifest["changes"][i]["mode"]
            )
            applied.append(i)
    except Exception:
        # Restore only the files this transaction actually changed.
        for i in reversed(applied):
            item = manifest["changes"][i]
            if item["existed"]:
                atomic_write(
                    item["path"],
                    (folder / (str(i) + ".bak")).read_bytes(),
                    item["mode"],
                )
            else:
                Path(item["path"]).unlink()
        manifest["state"] = "failed-restored"
        atomic_write(folder / "manifest.json", encode(manifest))
        raise
    manifest["state"] = "applied"
    atomic_write(folder / "manifest.json", encode(manifest))
    return {
        "install_id": install_id,
        "changed_files": len(changes),
        "manifest": str(folder / "manifest.json"),
    }


def rollback(home, install_id):
    if not re.fullmatch(r"[a-f0-9]{32}", install_id):
        raise AicoError("Invalid install id")
    folder = no_links(Path(home) / "backups" / install_id)
    manifest = read_json(no_links(folder / "manifest.json"))
    if manifest["state"] != "applied":
        raise AicoError("Install is not in applied state")
    backups = {}
    # Preflight the entire transaction before modifying anything.
    for i, item in enumerate(manifest["changes"]):
        path = no_links(item["path"])
        if sha(current(path)) != item["after_sha256"]:
            raise AicoError("Installed file changed; refusing rollback: " + str(path))
        if item["existed"]:
            backups[i] = no_links(folder / (str(i) + ".bak")).read_bytes()
            if digest(backups[i]) != item["before_sha256"]:
                raise AicoError("Backup integrity check failed")
    for i, item in enumerate(manifest["changes"]):
        if item["existed"]:
            atomic_write(item["path"], backups[i], item["mode"])
        else:
            no_links(item["path"]).unlink()
    manifest["state"] = "rolled-back"
    atomic_write(folder / "manifest.json", encode(manifest))
    return {"install_id": install_id, "state": "rolled-back"}
